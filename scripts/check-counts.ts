/**
 * npm run validate:counts
 *
 * Fails when everyday or deep-dive sections fall short of (or exceed) their item counts, and
 * writes the coverage table to docs/COVERAGE.md. See the task spec for the rules.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EVERYDAY_SECTIONS } from "../src/data/pageLayout.ts";
import { SECTION_IDS } from "../src/data/deepdive.ts";

const root = join(import.meta.dirname, "..");
const countriesDir = join(root, "src", "data", "countries");
const DD_MIN = 6, DD_MAX = 8;
const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const research = existsSync(join(root, "docs", "RESEARCH.md")) ? readFileSync(join(root, "docs", "RESEARCH.md"), "utf8") : "";
const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
// shortcut: scarcity entry = any line of RESEARCH.md naming the year and section id; tighten when the list gets long.
const scarcityListed = (year: number, id: string) => research.split("\n").some((l) => l.includes(String(year)) && l.includes(id));

const failures: string[] = [];
const table: string[] = [];
const countries = readdirSync(countriesDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();

for (const c of countries) {
  if (!read(join(countriesDir, c, "country.json")).enabled) continue;
  const hasDD = existsSync(join(countriesDir, c, "deepdive"));
  const ids = Object.keys(EVERYDAY_SECTIONS);
  table.push(`\n### ${c}\n`, `| year | ${ids.join(" | ")}${hasDD ? " | " + SECTION_IDS.join(" | ") : ""} |`, `|${"---|".repeat(1 + ids.length + (hasDD ? SECTION_IDS.length : 0))}`);
  const years = readdirSync(join(countriesDir, c, "eras")).map((f) => f.replace(".json", "")).sort();
  for (const y of years) {
    const row: string[] = [y];
    const titles = new Map<string, string>();
    const dup = (where: string, title: string) => {
      const k = norm(title);
      if (titles.has(k)) failures.push(`${c} ${y}: "${title}" appears in ${titles.get(k)} and ${where}`);
      else titles.set(k, where);
    };
    const efile = join(countriesDir, c, "everyday", `${y}.json`);
    if (!existsSync(efile)) failures.push(`${c} ${y}: everyday file missing`);
    const ev = existsSync(efile) ? read(efile) : { sections: {} };
    for (const [id, { min }] of Object.entries(EVERYDAY_SECTIONS)) {
      const s = ev.sections[id];
      if (!s) { failures.push(`${c} ${y} everyday.${id}: missing`); row.push("✗ missing"); continue; }
      const n = s.items.length;
      const bad = n < min && !s.scarcityNote;
      if (bad) failures.push(`${c} ${y} everyday.${id}: ${n}/${min}`);
      row.push(`${n}/${min}${bad ? " ✗" : ""}`);
      for (const it of s.items) dup(`everyday.${id}`, it.title);
    }
    if (hasDD) {
      const dd = read(join(countriesDir, c, "deepdive", `${y}.json`));
      for (const id of SECTION_IDS) {
        const s = dd.sections[id];
        const items = s.items as { title: string; context?: boolean; todo?: boolean; kind: string; regionTag?: string; gender?: string }[];
        const n = items.length;
        const ok = n >= DD_MIN || (s.scarcityNote && n >= 4 && scarcityListed(Number(y), id));
        const where = `${c} ${y} dd.${id}`;
        if (!ok) failures.push(`${where}: ${n}/${DD_MIN}`);
        if (n > DD_MAX) failures.push(`${where}: ${n} > ${DD_MAX}`);
        if (items.filter((i) => i.context).length > 2) failures.push(`${where}: more than 2 context items`);
        if (items.filter((i) => i.todo).length > 1) failures.push(`${where}: more than 1 todo item`);
        if (id === "economy-business" && items.filter((i) => i.kind === "indicator").length < 3) failures.push(`${where}: fewer than 3 indicators`);
        if (id === "personalities" && !dd.speculative) {
          const women = items.filter((i) => i.gender && /^f/i.test(i.gender)).length;
          const regions = new Set(items.map((i) => i.regionTag).filter(Boolean)).size;
          if ((women < 2 || regions < 3) && !research.includes(`${y} personalities`)) failures.push(`${where}: ${women} women, ${regions} regions, no RESEARCH.md note`);
        }
        row.push(`${n}/${DD_MIN}${ok ? "" : " ✗"}`);
        for (const it of items) dup(`dd.${id}`, it.title);
      }
    }
    table.push(`| ${row.join(" | ")} |`);
  }
}

writeFileSync(join(root, "docs", "COVERAGE.md"), `# Coverage\n\nGenerated by \`npm run validate:counts\`. Cells are \`count/min\`; ✗ = below minimum.\n${table.join("\n")}\n`);
if (failures.length) {
  console.error(`✗ ${failures.length} count problem(s) (table in docs/COVERAGE.md):\n  - ${failures.join("\n  - ")}`);
  process.exit(1);
}
console.log("✓ counts ok");
