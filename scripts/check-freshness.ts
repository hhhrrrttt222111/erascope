/**
 * npm run check:freshness
 *
 * Lists every present-year (2026) item whose `checked` date is more than 90 days old, or that was never checked
 * (todo), grouped by country and section, and writes the list into docs/RESEARCH.md between the freshness markers.
 * A warning only: it never fails the build. Without --write it only prints the count (that is how `npm run validate` runs it).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PRESENT_YEAR } from "../src/data/present.ts";

const root = join(import.meta.dirname, "..");
const data = join(root, "src", "data", "countries");
const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const DAY = 86_400_000;
const STALE_DAYS = 90;
type Item = { id: string; checked?: string; todo?: boolean; scheduled?: boolean; forecast?: unknown };
const groups = new Map<string, string[]>();
const note = (group: string, line: string) => groups.set(group, [...(groups.get(group) ?? []), line]);
const judge = (group: string, it: Item) => {
  const age = it.checked ? Math.floor((Date.now() - Date.parse(it.checked)) / DAY) : null;
  if (it.todo || age === null) note(group, `${it.id}: never verified (todo)`);
  else if (age > STALE_DAYS) note(group, `${it.id}: checked ${it.checked}, ${age} days ago${it.scheduled ? " (scheduled: confirm it happened)" : ""}`);
};

for (const c of ["world", "in"]) {
  const era = join(data, c, "eras", `${PRESENT_YEAR}.json`);
  if (existsSync(era)) {
    const e = read(era);
    for (const key of ["morningRoutine", "places", "prices", "technology", "futureVisions", "headlines"]) for (const it of e[key] ?? []) judge(`${c} / era / ${key}`, it);
  }
  const ev = join(data, c, "everyday", `${PRESENT_YEAR}.json`);
  if (existsSync(ev)) for (const [sec, s] of Object.entries<{ items: Item[] }>(read(ev).sections)) for (const it of s.items) judge(`${c} / everyday / ${sec}`, it);
  const dd = join(data, c, "deepdive", `${PRESENT_YEAR}.json`);
  if (existsSync(dd)) for (const [sec, s] of Object.entries<{ items: Item[] }>(read(dd).sections)) for (const it of s.items) judge(`${c} / deep dive / ${sec}`, it);
}

const lines = ["<!-- freshness:start -->", `### ${PRESENT_YEAR} refresh list (generated by \`npm run check:freshness\`; items to recheck first)`, ""];
if (groups.size === 0) lines.push("Nothing is stale or unverified.");
for (const [g, items] of [...groups].sort()) lines.push(`**${g}** (${items.length})`, "", ...items.map((i) => `- ${i}`), "");
lines.push("<!-- freshness:end -->");
const p = join(root, "docs", "RESEARCH.md");
const text = readFileSync(p, "utf8");
const block = lines.join("\n");
const next = !process.argv.includes("--write") ? text : text.includes("<!-- freshness:start -->") ? text.replace(/<!-- freshness:start -->[\s\S]*?<!-- freshness:end -->/, () => block) : `${text.trimEnd()}\n\n${block}\n`;
if (next !== text) writeFileSync(p, next);
const total = [...groups.values()].reduce((n, l) => n + l.length, 0);
console.warn(`check:freshness: ${total} ${PRESENT_YEAR} item(s) to recheck (npm run check:freshness writes the list to docs/RESEARCH.md)`);
